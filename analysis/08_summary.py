"""Collect selected statistics from results/<panel>/*.csv into results/SUMMARY.md.

    python analysis/08_summary.py
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.config import RESULTS                    # noqa: E402

KEY = ['BASELINE', 'TSL07', 'TSL10', 'ATR4', 'MA_SMA200_OV_TP100', 'TP100']
STOP_PREFIX = ('SL', 'TSL', 'LOW', 'ATR', 'MA_')


def n(x, d=2):
    return f'{x:.{d}f}'.replace('-', '−')


def rng(s, d=2):
    return f'{n(s.min(), d)} to {n(s.max(), d)}'


def stats(base):
    d = RESULTS / base
    if not (d / 'vix_regime.csv').exists():
        return None
    read = lambda f: pd.read_csv(d / f)  # noqa: E731
    pm = read('pure_momentum.csv'); m = read('rules_144_metrics.csv'); rc = read('reality_check.csv').iloc[0]
    bd = read('benchmarks_drawdown.csv').set_index('rule'); es = read('entry_signals_63.csv')
    vx = read('vix_regime.csv'); tc = read('trading_costs.csv').set_index('sample')
    spy = pm[pm.strategy == 'SPY'].iloc[0]; mom = pm[pm.strategy != 'SPY']
    mi = m.set_index('code'); best = m.sort_values('sharpe_std').iloc[-1]
    stops = m[m.code.str.startswith(STOP_PREFIX)]; key = bd.loc[KEY]
    v0 = vx[vx.lag_weeks == 0]; v1 = vx[vx.lag_weeks == 1]
    t = tc.loc['TSL07 trades with a quote']; a = tc.loc['all ETF-weeks with a quote']
    s = {}
    s['Pure momentum', 'Sharpe, 8 strategies (1–12 month lookbacks)'] = rng(mom.sharpe)
    s['Pure momentum', 'MaxDD %, 8 strategies'] = rng(mom.max_dd, 0)
    s['Pure momentum', 'SPY: Sharpe / MaxDD %'] = f'{n(spy.sharpe)} / {n(spy.max_dd, 0)}'
    if base == 'lseg':
        sv = read('survivorship.csv'); w = sv.pivot(index='rule', columns='universe', values='sharpe')
        nd = sv[sv.universe == 'all_funds'].n_delisted_closed
        s['Survivorship', 'Sharpe change when delisted ETFs are dropped, key rules'] = rng(w.survivors_only - w.all_funds)
        s['Survivorship', 'Positions closed by a delisting, key rules'] = f'{nd.min()} to {nd.max()}'
    s['144 exit rules', 'Highest standard Sharpe (rule)'] = f'{n(best.sharpe_std)} ({best.code})'
    s['144 exit rules', 'Standard Sharpe: SPY / 60-40 (from 2003-10)'] = f'{n(rc.benchmark_sharpe_std)} / {n(bd.sharpe_std_6040.iloc[0])}'
    s['144 exit rules', 'Rules with a higher standard Sharpe than SPY'] = f'{int(rc.n_rules_above_benchmark)} of 144'
    s['144 exit rules', 'Reality Check p-value (Sharpe), best rule vs SPY'] = n(rc.p_RC_sharpe)
    s['144 exit rules', 'CAPM alpha % a year, key rules (max t)'] = f'{rng(key.alpha_annual_pct, 1)} ({n(key.t_alpha.max())})'
    s['Exit rules vs BASELINE', 'Sharpe: TSL07 / BASELINE'] = f"{n(mi.loc['TSL07', 'sharpe'])} / {n(mi.loc['BASELINE', 'sharpe'])}"
    s['Exit rules vs BASELINE', 'Standard Sharpe difference TSL07 − BASELINE (p)'] = \
        f"{n(bd.loc['TSL07', 'dSharpe_std_vs_BASELINE'])} ({n(bd.loc['TSL07', 'p_dSharpe_vs_BASELINE'])})"
    s['Exit rules vs BASELINE', 'Stop rules with a higher standard Sharpe than BASELINE'] = \
        f"{(stops.sharpe_std > mi.loc['BASELINE', 'sharpe_std']).sum()} of {len(stops)}"
    s['Drawdown', 'MaxDD %, key rules / SPY'] = f'{rng(key.max_dd, 0)} / {n(key.SPY_max_dd.iloc[0], 0)}'
    s['Drawdown', 'p-value, MaxDD rule − SPY'] = rng(key.p_dMaxDD_vs_SPY)
    s['Drawdown', 'Average cash %, key rules'] = rng(mi.loc[KEY, 'cash_avg_pct'], 0)
    s['Drawdown', 'MaxDD %, SPY + T-bill blend with the same volatility'] = rng(key.mix_max_dd, 0)
    s['Drawdown', 'p-value, MaxDD rule − same-volatility blend'] = rng(key.p_dMaxDD_vs_mix)
    s['Entry signals (63 combinations)', 'MaxDD %'] = rng(es.max_dd, 0)
    s['Entry signals (63 combinations)', 'Standard Sharpe (distinct values)'] = f'{rng(es.sharpe_std)} ({es.sharpe.round(3).nunique()})'
    rce = d / 'entry_signals_63_reality_check.csv'
    if rce.exists():
        s['Entry signals (63 combinations)', 'Reality Check p-value, best vs SPY'] = n(pd.read_csv(rce).iloc[0].p_RC_sharpe)
    s['Macro regimes', 'VIX > 25 same week: β pp/week (t)'] = f'{rng(v0.VIX_HIGH_b)} ({rng(v0.VIX_HIGH_t, 1)})'
    s['Macro regimes', 'VIX > 25 previous week: β pp/week (t)'] = f'{rng(v1.VIX_HIGH_b)} ({rng(v1.VIX_HIGH_t, 1)})'
    s['Trading costs', 'Half spread bp, TSL07 trades: median / p90'] = f"{n(t['median'], 1)} / {n(t.p90, 1)}"
    s['Trading costs', 'Half spread bp, all ETF-weeks: median / p90'] = f"{n(a['median'], 1)} / {n(a.p90, 1)}"
    s['Trading costs', 'TSL07 trades at or below 20 bp'] = f'{n(t.share_at_or_below_20bp, 0)}%'
    s['Trading costs', 'TSL07 trades with a quote / ETFs with quotes'] = \
        f'{int(t.n)} / {int(t.etfs_traded_with_quotes)} of {int(t.etfs_traded)}'
    return s


if __name__ == '__main__':
    y, l = stats('yahoo'), stats('lseg')
    keys = list(dict.fromkeys(list(y or {}) + list(l or {})))
    out = ['# Summary of results', '',
           'Generated by `analysis/08_summary.py` from the CSV files in this folder. Weekly data, 2001-08 to 2026-05. '
           '"Sharpe" is (CAGR − 3%) / annualised volatility; "standard Sharpe" is the mean weekly excess return over '
           'the T-bill divided by its standard deviation, × √52. Key rules: ' + ', '.join(KEY) + '. p-values: '
           'stationary bootstrap, mean block 12 weeks, 2,000 replications.', '',
           '| Test | Statistic | Yahoo panel | LSEG panel |', '|---|---|---|---|']
    for k in keys:
        out.append(f'| {k[0]} | {k[1]} | {(y or {}).get(k, "—")} | {(l or {}).get(k, "—")} |')
    (RESULTS / 'SUMMARY.md').write_text('\n'.join(out) + '\n')
    print('\n'.join(out))
